// Copy wallet-selector's modal CSS without its Google Fonts @import, so the
// site stays on one (system) font and makes no third-party font request.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const src = readFileSync(require.resolve("@near-wallet-selector/modal-ui/styles.css"), "utf8");
const out = src.replace(/@import\s+url\([^)]*fonts\.googleapis[^)]*\)\s*;?/g, "").replace(/font-family:\s*[^;]*Inter[^;]*;/g, "font-family: inherit;");
if (/googleapis/.test(out)) throw new Error("modal CSS still references Google Fonts");
writeFileSync(new URL("../app/wallet-modal.css", import.meta.url), "/* generated by scripts/modal-css.mjs; do not edit */\n" + out);
